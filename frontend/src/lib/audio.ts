/**
 * Zero-dependency Web Audio API synthesizer for Tech Tombola.
 * Generates tactile auditory feedback for marking, clues, and prize claims.
 * Gracefully silent if Web Audio is unsupported or if muted by the user.
 */

const AUDIO_STORAGE_KEY = 'tt_audio_enabled';

let audioCtx: AudioContext | null = null;

function getAudioContext(): AudioContext | null {
  if (typeof window === 'undefined') return null;
  if (!audioCtx) {
    const AudioContextClass = window.AudioContext || (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
    if (AudioContextClass) {
      audioCtx = new AudioContextClass();
    }
  }
  if (audioCtx && audioCtx.state === 'suspended') {
    void audioCtx.resume();
  }
  return audioCtx;
}

export function isAudioEnabled(): boolean {
  if (typeof window === 'undefined') return false;
  const saved = localStorage.getItem(AUDIO_STORAGE_KEY);
  // Default to enabled (true) unless explicitly muted
  return saved === null ? true : saved === 'true';
}

export function setAudioEnabled(enabled: boolean): void {
  if (typeof window === 'undefined') return;
  localStorage.setItem(AUDIO_STORAGE_KEY, enabled ? 'true' : 'false');
}

/**
 * Play a gentle tactile mark chime (two quick sine pulses: 523Hz -> 659Hz)
 */
export function playMarkSound(): void {
  if (!isAudioEnabled()) return;
  try {
    const ctx = getAudioContext();
    if (!ctx) return;
    const now = ctx.currentTime;

    const osc = ctx.createOscillator();
    const gain = ctx.createGain();

    osc.type = 'sine';
    osc.frequency.setValueAtTime(523.25, now); // C5
    osc.frequency.exponentialRampToValueAtTime(659.25, now + 0.08); // E5

    gain.gain.setValueAtTime(0.12, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.15);

    osc.connect(gain);
    gain.connect(ctx.destination);

    osc.start(now);
    osc.stop(now + 0.15);
  } catch {
    // Audio failures should never interrupt gameplay
  }
}

/**
 * Play a subtle downward unmark click (440Hz -> 330Hz)
 */
